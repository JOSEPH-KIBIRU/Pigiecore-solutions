-- ===== templates table =====
create table if not exists templates (
  id bigint generated by default as identity primary key,
  created_at timestamp with time zone default now() not null,
  updated_at timestamp with time zone default now() not null,
  name text not null,
  description text not null,
  image_url text,
  category text not null,
  icon_name text not null default 'Home',
  gradient_from text not null default 'sky-500',
  gradient_to text not null default 'blue-600',
  preview_gradient text not null default 'from-sky-400 via-blue-500 to-indigo-600',
  sort_order integer default 0,
  url text
);

alter table templates enable row level security;

drop policy if exists "Allow public reads" on templates;
drop policy if exists "Allow authenticated inserts" on templates;
drop policy if exists "Allow authenticated updates" on templates;
drop policy if exists "Allow authenticated deletes" on templates;

create policy "Allow public reads"
  on templates
  for select
  to anon, authenticated
  using (true);

create policy "Allow authenticated inserts"
  on templates
  for insert
  to authenticated
  with check (true);

create policy "Allow authenticated updates"
  on templates
  for update
  to authenticated
  using (true)
  with check (true);

create policy "Allow authenticated deletes"
  on templates
  for delete
  to authenticated
  using (true);

