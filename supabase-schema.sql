-- ===== Storage bucket for template images =====
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('templates', 'templates', true, 5242880, array['image/png', 'image/jpeg', 'image/webp', 'image/gif'])
on conflict (id) do nothing;

-- Allow authenticated users to upload
drop policy if exists "Allow authenticated uploads" on storage.objects;
create policy "Allow authenticated uploads"
  on storage.objects
  for insert
  to authenticated
  with check (bucket_id = 'templates');

-- Allow public to view
drop policy if exists "Allow public to view templates" on storage.objects;
create policy "Allow public to view templates"
  on storage.objects
  for select
  to anon, authenticated
  using (bucket_id = 'templates');

-- Allow authenticated to delete
drop policy if exists "Allow authenticated deletes on templates" on storage.objects;
create policy "Allow authenticated deletes on templates"
  on storage.objects
  for delete
  to authenticated
  using (bucket_id = 'templates');

